"""PostgreSQL account, session and phone ownership storage for one MasterHub server."""
from contextlib import contextmanager
import hashlib
import os
import re
import secrets
import threading

import psycopg
from psycopg.conninfo import make_conninfo
from psycopg.rows import dict_row
import time
import uuid

from werkzeug.security import check_password_hash, generate_password_hash
from dotenv import load_dotenv

load_dotenv()

DEFAULT_DATABASE = os.getenv('DATABASE_URL', '')
_SCHEMA_LOCK = threading.Lock()
_INITIALIZED = set()
SCHEMA = (
    "CREATE TABLE IF NOT EXISTS runtime_events (sequence BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, event_id TEXT NOT NULL UNIQUE, instance_id TEXT NOT NULL, received_at BIGINT NOT NULL, kind TEXT NOT NULL, device_id TEXT NOT NULL, status TEXT NOT NULL, command_id TEXT, topic TEXT NOT NULL, payload JSONB NOT NULL)",
    "CREATE INDEX IF NOT EXISTS runtime_events_instance_time ON runtime_events(instance_id, received_at DESC, sequence DESC)",
    "CREATE INDEX IF NOT EXISTS runtime_events_device_time ON runtime_events(instance_id, device_id, received_at DESC)",
    "CREATE INDEX IF NOT EXISTS runtime_events_command ON runtime_events(instance_id, command_id)",
    "CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, created_at BIGINT NOT NULL)",
    "CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL)",
    "CREATE TABLE IF NOT EXISTS mobile_devices (device_id TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), installation_id TEXT NOT NULL, name TEXT NOT NULL, UNIQUE(user_id, installation_id))",
    "CREATE TABLE IF NOT EXISTS device_registry (id INTEGER PRIMARY KEY CHECK(id=1), payload TEXT NOT NULL)",
    "CREATE TABLE IF NOT EXISTS mqtt_devices (device_id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, device_type TEXT NOT NULL, updated_at BIGINT NOT NULL)",
)


def connection_info(dsn=None):
    if dsn is not None and not isinstance(dsn, str):
        raise ValueError('Use a PostgreSQL connection string, not a SQLite file path')
    value = dsn or os.getenv('DATABASE_URL', '')
    if value:
        return make_conninfo(value)
    return make_conninfo(host=os.getenv('PGHOST', 'localhost'), port=os.getenv('PGPORT', '5432'),
                         dbname=os.getenv('PGDATABASE', 'masterhub'), user=os.getenv('PGUSER', 'masterhub_app'),
                         password=os.getenv('PGPASSWORD', ''))


@contextmanager
def database(path=None):
    """Commit successful operations; roll back failures and always close connections."""
    info = connection_info(path)
    with psycopg.connect(info, connect_timeout=5, row_factory=dict_row) as connection:
        with _SCHEMA_LOCK:
            if info not in _INITIALIZED:
                with connection.transaction():
                    # Serialize initial schema creation across Masterhub processes.
                    connection.execute('SELECT pg_advisory_xact_lock(742819305)')
                    for statement in SCHEMA:
                        connection.execute(statement)
                _INITIALIZED.add(info)
        yield connection


def credentials(payload):
    username = payload.get('username')
    password = payload.get('password')
    if not isinstance(username, str) or not re.fullmatch(r'[A-Za-z0-9_]{3,32}', username.strip()):
        raise ValueError('Username must contain 3–32 letters, numbers or underscores')
    if not isinstance(password, str) or not 8 <= len(password) <= 128:
        raise ValueError('Password must contain 8–128 characters')
    return username.strip().lower(), password


def token_hash(token):
    return hashlib.sha256(token.encode()).hexdigest()


def authenticate(path, payload, register=False):
    username, password = credentials(payload)
    password_hash = generate_password_hash(password) if register else None
    with database(path) as db:
        if register:
            try:
                db.execute('INSERT INTO users(username,password_hash,created_at) VALUES(%s,%s,%s)',
                           (username, password_hash, int(time.time() * 1000)))
            except psycopg.errors.UniqueViolation:
                raise ValueError('Username is already registered') from None
        user = db.execute('SELECT * FROM users WHERE username=%s', (username,)).fetchone()
        if not user or (not register and not check_password_hash(user['password_hash'], password)):
            raise PermissionError('Invalid username or password')
        now = int(time.time() * 1000)
        expires = now + 30 * 24 * 60 * 60 * 1000
        token = secrets.token_urlsafe(32)
        db.execute('DELETE FROM sessions WHERE expires_at<=%s', (now,))
        db.execute('INSERT INTO sessions VALUES(%s,%s,%s)', (token_hash(token), user['id'], expires))
        return dict(token=token, expires_at=expires, user=dict(id=user['id'], username=user['username']))


def session_user(path, token):
    if not token or len(token) > 256:
        return None
    with database(path) as db:
        row = db.execute('''SELECT users.id, users.username FROM sessions JOIN users ON users.id=sessions.user_id
                            WHERE token_hash=%s AND expires_at>%s''', (token_hash(token), int(time.time() * 1000))).fetchone()
        return dict(row) if row else None


def register_phone(path, user_id, payload):
    installation = payload.get('installation_id')
    name = payload.get('name')
    if not isinstance(installation, str) or not re.fullmatch(r'[A-Za-z0-9_-]{16,100}', installation):
        raise ValueError('Invalid phone installation ID')
    if not isinstance(name, str) or not 1 <= len(name.strip()) <= 100:
        raise ValueError('Phone name must contain 1–100 characters')
    if payload.get('device_category') != 'mobile' or payload.get('platform') != 'android':
        raise ValueError('Expected an Android mobile device')
    with database(path) as db:
        db.execute('''INSERT INTO mobile_devices VALUES(%s,%s,%s,%s)
                      ON CONFLICT(user_id,installation_id) DO UPDATE SET name=excluded.name''',
                   ('MOBILE_' + uuid.uuid4().hex, user_id, installation, name.strip()))
        return dict(db.execute('SELECT * FROM mobile_devices WHERE user_id=%s AND installation_id=%s',
                               (user_id, installation)).fetchone())
