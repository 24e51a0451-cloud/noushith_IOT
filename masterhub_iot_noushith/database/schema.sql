-- Masterhub PostgreSQL initial schema. Kept in sync with core/account_store.py SCHEMA.

CREATE TABLE IF NOT EXISTS runtime_events (sequence BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, event_id TEXT NOT NULL UNIQUE, instance_id TEXT NOT NULL, received_at BIGINT NOT NULL, kind TEXT NOT NULL, device_id TEXT NOT NULL, status TEXT NOT NULL, command_id TEXT, topic TEXT NOT NULL, payload JSONB NOT NULL);

CREATE INDEX IF NOT EXISTS runtime_events_instance_time ON runtime_events(instance_id, received_at DESC, sequence DESC);

CREATE INDEX IF NOT EXISTS runtime_events_device_time ON runtime_events(instance_id, device_id, received_at DESC);

CREATE INDEX IF NOT EXISTS runtime_events_command ON runtime_events(instance_id, command_id);

CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, created_at BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS mobile_devices (device_id TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), installation_id TEXT NOT NULL, name TEXT NOT NULL, UNIQUE(user_id, installation_id));

CREATE TABLE IF NOT EXISTS device_registry (id INTEGER PRIMARY KEY CHECK(id=1), payload TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS mqtt_devices (device_id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, device_type TEXT NOT NULL, updated_at BIGINT NOT NULL);
